}

# exec_system SYSTEM WL STEP VARIANT NONCE STAGEDIR
# Runs one system once on a fresh copy of STAGEDIR and appends one CSV row.
exec_system() {
    local sys=$1 wl=$2 stepn=$3 variant=$4 nonce=$5 stage=$6
    local wd=$RUNROOT/$wl-$stepn-$sys-$variant logd=$RES/logs rc=0 mode="" prefix=""
    mkdir -p "$logd"; rm -rf "$wd"; mkdir -p "$wd"; cp -a "$stage/." "$wd/"
    local err=$logd/$wl-$stepn-$sys-$variant.err out=$logd/$wl-$stepn-$sys-$variant.out
    : >"$err"; : >"$out"
    local r0 t0 r1 t1
    case "$sys" in
    zm-local|zm)
        local flags=()
        if [ "$sys" = zm-local ]; then flags=(--local-only); elif [ "$CUR_ALL" = 0 ]; then flags=(--remote-only); fi
        read -r r0 <<<"$(nic_read)"; t0=$(now)
        ( cd "$wd" && timeout "$ZMF_TIMEOUT" "$BUILD/zm" --socket "$SOCK" run ${flags[@]+"${flags[@]}"} \
            --each 'cases/*' -- sh ./sim.sh '{}' "$nonce" ) >"$out" 2>"$err" || rc=$?
        t1=$(now); read -r r1 <<<"$(nic_read)"
        prefix=cases/ ;;
    condor-*)
        mode=${sys#condor-}
        condor_set_mode "$mode"
        condor_submit_file "$wd" "$wl" "$nonce" "$mode"
        condor_stage_in "$wd"
        read -r r0 <<<"$(nic_read)"; t0=$(now)
        condor_submit_wait "$wd" >"$out" 2>"$err" || rc=$?
        t1=$(now); read -r r1 <<<"$(nic_read)"
        condor_stage_out "$wd"
        prefix="" ;;
    *) die "unknown system $sys" ;;
    esac
    # NIC counters are "rx tx" pairs; split them
    local rx0 tx0 rx1 tx1
    rx0=${r0%% *}; tx0=${r0##* }; rx1=${r1%% *}; tx1=${r1##* }
    local total=0 okc=0 c
    while read -r c; do
        total=$((total+1))
        if grep -q '^ok' "$wd/$prefix$c.out" 2>/dev/null; then okc=$((okc+1)); fi
    done <"$STAGE_NAMES"
    local retries=0
    if [ "${sys#zm}" != "$sys" ]; then retries=$(grep -cE 'retry [0-9]+/[0-9]+' "$err" || true); fi
    local note="rc=$rc"
    [ "$sys" = zm ] && [ "$CUR_ALL" = 0 ] && note="$note;remote-only"
    [ "$sys" = zm ] && [ "$CUR_ALL" = 1 ] && note="$note;all-nodes"
    [ "${sys#condor}" != "$sys" ] && [ "$CUR_ALL" = 1 ] && note="$note;all-nodes"
    [ -n "${KILL_NOTE:-}" ] && note="$note;$KILL_NOTE"
    printf '%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,%s\n' "$wl" "$stepn" "$sys" "$variant" \
        "$(awk -v a="$t0" -v b="$t1" 'BEGIN{printf "%.2f", b-a}')" \
        "$(awk -v a="$rx0" -v b="$rx1" 'BEGIN{printf "%.1f", (b-a)/1048576}')" \
        "$(awk -v a="$tx0" -v b="$tx1" 'BEGIN{printf "%.1f", (b-a)/1048576}')" \
        "$okc" "$total" "$retries" "$note" >>"$CSV"
    log "$wl/$stepn $sys/$variant: $(awk -v a="$t0" -v b="$t1" 'BEGIN{printf "%.1fs", b-a}'), ok $okc/$total, retries $retries, $note"
}

chaos_trigger() { # chaos_trigger KIND MODE   (KIND: zm|condor, MODE: kill|term|restore)
    local kind=$1 mode=$2
    if [ -n "$SSH_TARGET" ]; then
        ssh -o BatchMode=yes -o ConnectTimeout=10 "$SSH_TARGET" "bash $SSH_SCRIPT chaos $kind $mode" \
            || warn "ssh chaos $kind $mode failed (condor kills need passwordless sudo on the donor)"
    else
        printf '\n%s>>> ON THE DONOR RUN NOW:  bash scripts/zmfield.sh chaos %s %s%s\n' "$C_B" "$kind" "$mode" "$C_0" >&2
        read -r -p ">>> press ENTER the moment you have run it: " _ </dev/tty || true
    fi
}

wait_pool_ready() {
    local i
    for i in $(seq 1 90); do
        if [ "$(admitted_peers)" -ge 1 ]; then break; fi
        sleep 2
    done
    if [ "$(admitted_peers)" -lt 1 ]; then warn "donor not back in zm status after 3 min"; fi
    if [ "$CONDOR_OK" = 1 ]; then
        for i in $(seq 1 90); do
            if [ "$(condor_machines | wc -l)" -ge 2 ]; then return 0; fi
            sleep 2
        done
        warn "donor slot not back in condor_status after 3 min"
    fi
}

STAGE_NAMES=""
condor_systems() {
    local m
    if [ "$CONDOR_OK" = 1 ]; then
        for m in ${CONDOR_MODES//,/ }; do printf 'condor-%s ' "$m"; done
    fi
    return 0
}
systems_list() { echo "zm-local zm $(condor_systems)"; }

bench_w1() {
    step "w1: CPU fan-out, $NCASES cases of ~${SECS}s"
    local stage=$RUNROOT/stage-w1 sys; CUR_ALL=$ALL_NODES
    rm -rf "$stage"; stage_cpu "$stage" "$NCASES"; ls "$stage/cases" >"$STAGE_NAMES"
    for sys in $(systems_list); do exec_system "$sys" w1 main none "$RUNID-w1-$sys" "$stage"; done
}

bench_w2() {
    local n=12
    step "w2: data-once, $n tasks over a ${MB} MB input, then one case changed"
    local stage=$RUNROOT/stage-w2 stage2=$RUNROOT/stage-w2b sys; CUR_ALL=$ALL_NODES
    rm -rf "$stage" "$stage2"; stage_data "$stage" "$n" "$MB"; ls "$stage/cases" >"$STAGE_NAMES"
    cp -a "$stage" "$stage2"; echo "changed" >>"$stage2/cases/003"
    for sys in $(systems_list); do
        exec_system "$sys" w2 first none "$RUNID-w2-$sys" "$stage"
        # same nonce: zm may reuse cached tasks whose input did not change (per-task input roots)
        exec_system "$sys" w2 one-case-changed none "$RUNID-w2-$sys" "$stage2"
    done
}

bench_w3() {
    local n=$((NCASES + NCASES * 2 / 3))
    step "w3: churn, $n cases, donor killed at ~30% (needs a second node to finish on)"
    [ "$ALL_NODES" = 1 ] || log "w3 forces all-nodes: the requester must be able to finish the work after the donor dies"
    CUR_ALL=1
    local stage=$RUNROOT/stage-w3 sys base_wall delay modes="kill" mode kind pid
    rm -rf "$stage"; stage_cpu "$stage" "$n"; ls "$stage/cases" >"$STAGE_NAMES"
    if [ "$WITH_TERM" = 1 ]; then modes="kill term"; fi
    exec_system zm-local w3 main none "$RUNID-w3-local" "$stage"
    # control: the pool with no kill. The kill time comes from this run, not from zm-local, because
    # the whole pool finishes well before one machine would.
    exec_system zm w3 main none "$RUNID-w3-zm-control" "$stage"
    base_wall=$(awk -F, '$1=="w3" && $3=="zm" && $4=="none"{w=$5} END{print w+0}' "$CSV")
    delay=$(awk -v w="$base_wall" 'BEGIN{printf "%.1f", w*0.3}')
    log "kill delay ${delay}s (30% of the pool's no-kill ${base_wall}s)"
    for mode in $modes; do
        for sys in zm $(condor_systems); do
            kind=zm
            if [ "${sys#condor}" != "$sys" ]; then
                kind=condor
                # switch HTCondor mode here, not in the background job, so the kill timer stays accurate
                condor_set_mode "${sys#condor-}"
            fi
            KILL_NOTE="kill_after=${delay}s"
            exec_system "$sys" w3 main "$mode" "$RUNID-w3-$sys-$mode" "$stage" &
            pid=$!
            sleep "$delay"
            chaos_trigger "$kind" "$mode"
            wait "$pid" || warn "run $sys/$mode ended abnormally"
            KILL_NOTE=""
            chaos_trigger "$kind" restore
            wait_pool_ready
        done
    done
}

cmd_bench() {
    while [ $# -gt 0 ]; do
        case "$1" in
        --workloads) WORKLOADS=${2:?}; shift ;;
        --cases) NCASES=${2:?}; shift ;;
        --secs) SECS=${2:?}; shift ;;
        --mb) MB=${2:?}; shift ;;
        --all-nodes) ALL_NODES=1 ;;
        --ssh) SSH_TARGET=${2:?}; shift ;;
        --ssh-script) SSH_SCRIPT=${2:?}; shift ;;
        --condor-modes) CONDOR_MODES=${2:?}; shift ;;
        --peer) PEER_IP=${2:?}; shift ;;
        --with-term) WITH_TERM=1 ;;
        *) die "bench: unknown option $1" ;;
        esac
        shift
    done
    load_env
    if [ "$DRY" = 1 ]; then
        step "bench plan (dry-run)"
        log "workloads: $WORKLOADS   cases=$NCASES secs=$SECS mb=$MB all-nodes=$ALL_NODES"
        log "systems per workload: zm-local zm $(for m in ${CONDOR_MODES//,/ }; do printf 'condor-%s ' "$m"; done)"
        log "w1 CPU fan-out | w2 data-once then one case changed | w3 donor killed at ~30% (add --with-term for a SIGTERM variant)"
        log "results -> $ZMF_HOME/results/<UTC-timestamp>/{results.csv,report.md,hostinfo.txt,logs/}"
        return 0
    fi
    [ -x "$BUILD/zm" ] || die "not built: run setup first"
    zmd_alive || die "zmd is not running: run 'requester' first"
    [ "$(admitted_peers)" -ge 1 ] || die "no ADMITTED peer in 'zm status'; get the donor joined first"

    local target=$PEER_IP
    if [ -z "$target" ] && [ -f "$ZMF_HOME/state/peer_ip" ]; then target=$(cat "$ZMF_HOME/state/peer_ip"); fi
    if [ -z "$target" ]; then target=$(ZM status 2>/dev/null | grep -o -E '\(([0-9]+\.){3}[0-9]+:[0-9]+\)' | head -1 | tr -d '()' | cut -d: -f1 || true); fi
    if [ -n "$target" ]; then IFACE=$(iface_for "$target"); fi
    if [ -z "$IFACE" ]; then
        IFACE=$(iface_for 1.1.1.1)
        warn "could not work out the NIC towards the donor (pass --peer IP); using $IFACE. NIC byte counts also include unrelated traffic on that interface"
    fi
    log "measuring bytes on $IFACE (rx+tx on the requester; includes any other traffic on that NIC)"

    CONDOR_OK=0
    if [ "$(condor_tier)" != none ]; then
        if [ "$(condor_machines | wc -l)" -ge 2 ]; then CONDOR_OK=1
        else warn "condor_status shows fewer than 2 machines: HTCondor runs are SKIPPED. Is the donor's startd up and 9618/tcp open?"; fi
    else
        warn "no HTCondor on this machine: HTCondor runs are SKIPPED"
    fi

    RUNID=$(date -u +%Y%m%dT%H%M%SZ)
    RES=$ZMF_HOME/results/$RUNID; RUNROOT=$ZMF_HOME/work/$RUNID; CSV=$RES/results.csv
    STAGE_NAMES=$RUNROOT/names.txt
    mkdir -p "$RES/logs" "$RUNROOT"
    echo 'workload,step,system,variant,wall_s,rx_mb,tx_mb,ok,total,retries,notes' >"$CSV"
    calibrate
    write_hostinfo

    local wl
    for wl in ${WORKLOADS//,/ }; do
        case "$wl" in
        w1) bench_w1 ;;
        w2) bench_w2 ;;
        w3) bench_w3 ;;
        *) warn "unknown workload $wl" ;;
        esac
    done
    if [ "${ZMF_KEEP_WORK:-0}" != 1 ]; then rm -rf "$RUNROOT"; fi
    cmd_report "$RES"
}

