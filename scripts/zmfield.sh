cmd_requester() {
    local ip="" peer="" mode=default
    while [ $# -gt 0 ]; do
        case "$1" in
        --ip) ip=${2:?}; shift ;;
        --peer) peer=${2:?}; shift ;;
        --condor-mode) mode=${2:?}; shift ;;
        *) die "requester: unknown option $1" ;;
        esac
        shift
    done
    load_env
    [ -n "$ip" ] || ip=$(detect_ip)
    [ -n "$ip" ] || die "cannot detect the LAN IP; pass --ip"
    step "requester at $ip"
    zmd_start
    run mkdir -p "$ZMF_HOME/state"
    if [ "$DRY" = 0 ]; then
        echo "$ip" >"$ZMF_HOME/state/cm_ip"
        if [ -n "$peer" ]; then echo "$peer" >"$ZMF_HOME/state/peer_ip"; fi
    fi
    local phrase=""
    if [ "$DRY" = 1 ]; then phrase="'ZM-XXXX-DRY-RUN'"
    elif ZM team info 2>/dev/null | grep -q '^team_id'; then
        if [ -f "$ZM_DIR/phrase" ]; then phrase=$(cat "$ZM_DIR/phrase"); log "already in a team; reusing the saved phrase"
        else
            log "in a team whose phrase was not saved; leaving it and creating a fresh test team"
            ZM team leave || true
            phrase=$(ZM team create); echo "$phrase" >"$ZM_DIR/phrase"
        fi
    else
        phrase=$(ZM team create); echo "$phrase" >"$ZM_DIR/phrase"
    fi
    condor_start requester "$ip" "$ip" "$peer"
    if [ "$mode" = tuned ]; then condor_set_mode tuned; else CONDOR_MODE_CUR=default; fi
    step "run this on the donor laptop"
    printf '    bash scripts/zmfield.sh donor --cm %s --ip <donor-ip> --join %s\n' "$ip" "$phrase"
    if [ -z "$peer" ]; then
        log "tip: restart with 'requester --peer <donor-ip>' to replace the subnet-wide HTCondor allow-list with the donor's address"
    fi
    if [ "$DRY" = 1 ]; then return 0; fi
    log "waiting up to 60s for an ADMITTED peer in 'zm status'"
    if wait_admitted 60; then log "peer admitted:"; ZM status | sed 's/^/    /'
    else warn "no admitted peer after 60s. Check: same LAN/multicast reachable, 8981/tcp + 8988/udp open, donor ran the join command"; fi
}

cmd_donor() {
    local ip="" cm="" phrase="${ZMF_PHRASE:-}"
    while [ $# -gt 0 ]; do
        case "$1" in
        --cm) cm=${2:?}; shift ;;
        --ip) ip=${2:?}; shift ;;
        --join) phrase=${2:?}; shift ;;
        *) die "donor: unknown option $1" ;;
        esac
        shift
    done
    [ -n "$cm" ] || die "donor: --cm <requester-ip> is required"
    load_env
    [ -n "$ip" ] || ip=$(detect_ip)
    [ -n "$ip" ] || die "cannot detect the LAN IP; pass --ip"
    step "donor at $ip (requester $cm)"
    zmd_start
    run mkdir -p "$ZMF_HOME/state"
    if [ "$DRY" = 0 ]; then echo "$cm" >"$ZMF_HOME/state/cm_ip"; fi
    if [ "$DRY" = 1 ]; then log "(dry-run) would join the team"
    elif ZM team info 2>/dev/null | grep -q '^team_id'; then log "already in a team"
    else
        if [ -z "$phrase" ]; then read -r -p "team phrase from the requester (quote-free): " phrase; fi
        [ -n "$phrase" ] || die "no team phrase"
        phrase=${phrase#\'}; phrase=${phrase%\'}
        ZM team join "$phrase"
    fi
    # the requester's own IP is the only host that needs to talk to this machine's startd/master
    condor_start donor "$cm" "$ip" "$cm"
    if [ "$DRY" = 0 ]; then ZM status | sed 's/^/    /' || true; fi
    log "donor ready. Leave this machine alone (plugged in, awake). zmd runs in the background (pid file $ZMD_PID)."
}

cmd_down() {
    load_env
    step "stopping zmd and HTCondor"
    zmd_stop
    condor_stop
    log "state kept in $ZMF_HOME (results, builds untouched). Remove it by hand if you want a clean slate."
}

# chaos: run on the DONOR. Used by the requester's bench (over --ssh) or by hand.
cmd_chaos() {
    local kind=${1:-} mode=${2:-kill}
    load_env
    case "$kind:$mode" in
    zm:kill) if zmd_alive; then run kill -KILL "$(cat "$ZMD_PID")"; else warn "zmd not running"; fi ;;
    zm:term) if zmd_alive; then run kill -TERM "$(cat "$ZMD_PID")"; else warn "zmd not running"; fi ;;
    condor:kill)
        case "$(condor_tier)" in
        native) as_root pkill -9 -x condor_master || true; as_root pkill -9 -x condor_startd || true; as_root pkill -9 -x condor_starter || true ;;
        container) run "$(ctr)" kill "$CNAME" ;;
        esac ;;
    condor:term)
        case "$(condor_tier)" in
        native) if have systemctl; then as_root systemctl stop condor; else as_root pkill -TERM -x condor_master; fi ;;
        container) run "$(ctr)" stop "$CNAME" ;;
        esac ;;
    *:restore)
        # bring the donor back after a chaos run
        zmd_start
        case "$(condor_tier)" in
        native) if have systemctl; then as_root systemctl restart condor; else as_root condor_master; fi ;;
        container) run "$(ctr)" start "$CNAME" ;;
        esac ;;
    *) die "usage: chaos <zm|condor> <kill|term|restore>" ;;
    esac
}

