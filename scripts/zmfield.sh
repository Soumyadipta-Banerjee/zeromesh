#!/usr/bin/env bash
# zmfield.sh: field-test ZeroMesh against HTCondor on two (or more) real Linux laptops.
#
#   bash scripts/zmfield.sh --help          (use `bash` even if your login shell is fish)
#
# What it does: checks/installs dependencies, builds zeromesh, starts a zmd team and an
# HTCondor pool spanning the same machines, runs the same payload through ZeroMesh and
# HTCondor, and writes timing / bytes-moved / correctness numbers to a results directory.
#
# STATUS: written without being run. Only `bash -n`, --help, doctor and --dry-run were
# exercised when it was written. The v2-integration build, other-distro package names, the
# HTCondor config knobs and auth settings, the container fallback and everything that needs
# two machines are UNVERIFIED. When something here disagrees with reality, trust the machine.
#
# Linux only (zeromesh needs bubblewrap, cgroup v2, FUSE). Needs bash >= 4.
set -euo pipefail

SCRIPT_PATH=$(readlink -f "${BASH_SOURCE[0]}")
SCRIPT_DIR=$(dirname "$SCRIPT_PATH")
ROOT=$(cd "$SCRIPT_DIR/.." && pwd)

ZMF_HOME=${ZMF_HOME:-$HOME/.zmfield}
BUILD=${ZMF_BUILD:-$ROOT/build}
PREFIX=$ZMF_HOME/prefix
VENV=$ZMF_HOME/venv
ZM_DIR=$ZMF_HOME/zm
ZMF_BWRAP_TAG=${ZMF_BWRAP_TAG:-v0.12.0}
ZMF_TIMEOUT=${ZMF_TIMEOUT:-1800}
CONDOR_IMAGE=${ZMF_CONDOR_IMAGE:-docker.io/htcondor/mini:lts}
CNAME=zmf-condor
BWRAP_MIN=0.12.0

# zmd/zm state lives under ZMF_HOME so the test never touches the user's real team or store.
export ZM_STATE_DIR=$ZM_DIR/state
export ZM_RUNTIME_DIR=$ZM_DIR/run
export ZM_CONFIG_DIR=$ZM_DIR/config
export ZM_PLUGIN_PATH=""
SOCK=$ZM_RUNTIME_DIR/zmd.sock

DRY=0

# ---------------------------------------------------------------------------------------
# small helpers
# ---------------------------------------------------------------------------------------
if [ -t 2 ]; then C_R=$'\033[31m'; C_Y=$'\033[33m'; C_G=$'\033[32m'; C_B=$'\033[1m'; C_0=$'\033[0m'
else C_R=""; C_Y=""; C_G=""; C_B=""; C_0=""; fi

log()  { printf 'zmfield: %s\n' "$*"; }
step() { printf '\n%s== %s ==%s\n' "$C_B" "$*" "$C_0"; }
warn() { printf '%szmfield: WARN: %s%s\n' "$C_Y" "$*" "$C_0" >&2; }
die()  { printf '%szmfield: ERROR: %s%s\n' "$C_R" "$*" "$C_0" >&2; exit 1; }
have() { command -v "$1" >/dev/null 2>&1; }

# run: execute a command, or only print it under --dry-run.
run() {
    if [ "$DRY" = 1 ]; then
        printf '+'; printf ' %q' "$@"; printf '\n' >&2
        return 0
    fi
    "$@"
}
# as_root: run through sudo unless already root. Only used for packages, services, firewall.
as_root() {
    if [ "$(id -u)" = 0 ]; then run "$@"; else run sudo "$@"; fi
}

now() { date +%s.%N; }

version_ge() { # version_ge A B  -> true if A >= B
    [ "$(printf '%s\n%s\n' "$1" "$2" | sort -V | tail -n1)" = "$1" ]
}

load_env() {
    local d
    for d in "$VENV/bin" "$PREFIX/bin"; do
        if [ -d "$d" ]; then PATH="$d:$PATH"; fi
    done
    # condor_master and friends live in sbin on most distros
    PATH="$PATH:/usr/sbin:/sbin:/usr/local/sbin"
    export PATH
}

write_env_sh() {
    [ "$DRY" = 1 ] && { log "(dry-run) would write $ZMF_HOME/env.sh"; return 0; }
    mkdir -p "$ZMF_HOME"
    cat >"$ZMF_HOME/env.sh" <<EOF
# generated by zmfield.sh; source it to get the same PATH and zm state the script uses
[ -d "$VENV/bin" ] && PATH="$VENV/bin:\$PATH"
[ -d "$PREFIX/bin" ] && PATH="$PREFIX/bin:\$PATH"
export PATH="\$PATH:$BUILD"
export ZM_STATE_DIR="$ZM_STATE_DIR" ZM_RUNTIME_DIR="$ZM_RUNTIME_DIR" ZM_CONFIG_DIR="$ZM_CONFIG_DIR" ZM_PLUGIN_PATH=""
alias zmf='zm --socket "$SOCK"'
EOF
}

detect_os() {
    OS_ID=unknown; OS_PRETTY=unknown
    if [ -r /etc/os-release ]; then
        OS_ID=$(. /etc/os-release; echo "${ID:-unknown}")
        OS_PRETTY=$(. /etc/os-release; echo "${PRETTY_NAME:-$OS_ID}")
    fi
    if have apt-get; then PM=apt
    elif have dnf; then PM=dnf
    elif have pacman; then PM=pacman
    elif have zypper; then PM=zypper
    else PM=none; fi
}

build_jobs() {
    if [ -n "${ZMF_JOBS:-}" ]; then echo "$ZMF_JOBS"; return; fi
    # ~600 MB per cc1plus on the gRPC/protobuf units; an unbounded build once killed a desktop session.
    awk -v n="$(nproc)" '/MemAvailable/{m=int($2/1258291); if(m<n)n=m; if(n>6)n=6; if(n<1)n=1; print n}' /proc/meminfo
}

detect_ip() {
    local ip=""
    ip=$(ip -4 route get 1.1.1.1 2>/dev/null | awk '{for(i=1;i<=NF;i++) if($i=="src"){print $(i+1); exit}}') || true
    if [ -z "$ip" ]; then ip=$(hostname -I 2>/dev/null | awk '{print $1}') || true; fi
    echo "$ip"
}

iface_for() { # iface_for IP
    ip -4 route get "$1" 2>/dev/null | awk '{for(i=1;i<=NF;i++) if($i=="dev"){print $(i+1); exit}}'
}

ctr() { # container runtime
    if have podman; then echo podman; elif have docker; then echo docker; else echo ""; fi
}

# ---------------------------------------------------------------------------------------
# doctor
# ---------------------------------------------------------------------------------------
FAILS=0; WARNS=0
c_ok()   { printf '  [%s ok %s] %s\n' "$C_G" "$C_0" "$*"; }
c_warn() { printf '  [%swarn%s] %s\n' "$C_Y" "$C_0" "$*"; WARNS=$((WARNS+1)); }
c_fail() { printf '  [%sFAIL%s] %s\n' "$C_R" "$C_0" "$*"; FAILS=$((FAILS+1)); }

cmd_doctor() {
    load_env; detect_os
    step "zmfield doctor"
    if [ "$(uname -s)" = Linux ]; then c_ok "Linux $(uname -r)"; else c_fail "not Linux: zeromesh cannot run here"; fi
    c_ok "distro: $OS_PRETTY, package manager: $PM"
    if [ "$PM" = none ]; then c_fail "no supported package manager (apt/dnf/pacman/zypper); install deps by hand"; fi

    local mem cores
    mem=$(awk '/MemAvailable/{printf "%.1f", $2/1048576}' /proc/meminfo)
    cores=$(nproc)
    c_ok "${cores} cores, ${mem} GiB RAM available, build -j$(build_jobs)"
    if awk -v m="$mem" 'BEGIN{exit !(m<4)}'; then c_warn "under 4 GiB free: the build may be OOM-killed (set ZMF_JOBS=1)"; fi

    if have bwrap; then
        local v; v=$(bwrap --version 2>/dev/null | awk '{print $2}')
        if [ -n "$v" ] && version_ge "$v" "$BWRAP_MIN"; then c_ok "bubblewrap $v (need >= $BWRAP_MIN)"
        else c_fail "bubblewrap ${v:-?} is older than $BWRAP_MIN; 'setup' builds $ZMF_BWRAP_TAG into $PREFIX"; fi
        if [ -u "$(command -v bwrap)" ]; then c_fail "bwrap is setuid; zmd refuses a setuid bwrap"; fi
        local err; err=$(bwrap --ro-bind / / true 2>&1) && c_ok "bwrap can create a sandbox" \
            || c_fail "bwrap sandbox failed: ${err:-no output}. On Ubuntu try: sudo sysctl kernel.apparmor_restrict_unprivileged_userns=0"
    else
        c_fail "bubblewrap not installed ('setup' installs it)"
    fi

    if [ -c /dev/fuse ]; then c_ok "/dev/fuse present"; else c_warn "no /dev/fuse: env-mirror tests will fail (not needed for this bench)"; fi
    if [ "$(stat -fc %T /sys/fs/cgroup 2>/dev/null || true)" = cgroup2fs ]; then c_ok "cgroup v2"; else c_warn "not cgroup v2: freeze-first departure cannot work"; fi

    local fw=none
    if have firewall-cmd && systemctl is-active --quiet firewalld 2>/dev/null; then fw=firewalld
    elif have ufw && { ufw status 2>/dev/null | grep -q 'Status: active' || systemctl is-active --quiet ufw 2>/dev/null; }; then fw=ufw; fi
    if [ "$fw" = none ]; then c_ok "no active ufw/firewalld seen (iptables/nftables rules not inspected)"
    else c_warn "$fw is active: open 8981/tcp 8988/udp (zeromesh) and 9618/tcp (HTCondor), or run: setup --open-firewall"; fi

    local c; c=$(ctr)
    if [ -n "$c" ]; then c_ok "container runtime: $c"; else c_warn "no podman/docker (HTCondor container fallback unavailable)"; fi
    if have condor_master || [ -x /usr/sbin/condor_master ]; then c_ok "HTCondor installed natively"; else c_warn "HTCondor not installed ('setup' will try)"; fi
    if [ -x "$BUILD/zm" ] && [ -x "$BUILD/zmd" ]; then c_ok "zeromesh built in $BUILD"; else c_warn "zeromesh not built yet ('setup')"; fi

    local b st
    for b in /sys/class/power_supply/BAT*; do
        [ -r "$b/status" ] || continue
        st=$(cat "$b/status")
        if [ "$st" = Discharging ]; then c_warn "on battery ($st): zmfield writes a donor.toml that donates anyway, but expect throttling and skewed numbers; plug in"
        else c_ok "battery: $st"; fi
    done
    if [ -z "$(detect_ip)" ]; then c_warn "no LAN IPv4 address found; pass --ip"; else c_ok "LAN address: $(detect_ip)"; fi

    printf '\n%d failure(s), %d warning(s)\n' "$FAILS" "$WARNS"
    [ "$FAILS" = 0 ]
}

# ---------------------------------------------------------------------------------------
# setup
# ---------------------------------------------------------------------------------------
install_deps() {
    detect_os
    step "installing build dependencies ($PM)"
    case "$PM" in
    apt)
        as_root apt-get update
        as_root apt-get install -y build-essential meson ninja-build pkg-config bubblewrap \
            libgrpc++-dev protobuf-compiler-grpc libprotobuf-dev protobuf-compiler libsodium-dev \
            libssl-dev libfuse3-dev fuse3 python3 python3-venv python3-pip python3-grpcio \
            python3-grpc-tools git curl iproute2 libcap-dev ;;
    pacman)
        as_root pacman -S --needed --noconfirm base-devel meson ninja bubblewrap grpc protobuf \
            libsodium openssl fuse3 python python-pip python-grpcio python-grpcio-tools git curl \
            iproute2 libcap ;;
    dnf)
        warn "dnf package list is UNTESTED"
        as_root dnf install -y gcc-c++ make meson ninja-build pkgconf-pkg-config bubblewrap \
            grpc-devel grpc-plugins protobuf-devel protobuf-compiler libsodium-devel openssl-devel \
            fuse3-devel python3 python3-pip python3-grpcio python3-grpcio-tools git curl iproute libcap-devel ;;
    zypper)
        warn "zypper package list is UNTESTED"
        as_root zypper --non-interactive install gcc-c++ make meson ninja pkg-config bubblewrap \
            grpc-devel protobuf-devel libsodium-devel libopenssl-devel fuse3-devel python3 python3-pip \
            python3-grpcio python3-grpcio-tools git curl iproute2 libcap-devel ;;
    *) die "no supported package manager; install: C++20 compiler, meson, ninja, bubblewrap>=$BWRAP_MIN, gRPC, protobuf, libsodium, openssl, fuse3, python3, git, curl, iproute2" ;;
    esac
}

ensure_bwrap() {
    step "bubblewrap >= $BWRAP_MIN"
    local v=""
    if have bwrap; then v=$(bwrap --version 2>/dev/null | awk '{print $2}'); fi
    if [ -n "$v" ] && version_ge "$v" "$BWRAP_MIN"; then log "bubblewrap $v is fine"; return 0; fi
    log "bubblewrap ${v:-missing} is too old; building $ZMF_BWRAP_TAG into $PREFIX"
    local src=$ZMF_HOME/src/bubblewrap
    run mkdir -p "$ZMF_HOME/src"
    if [ ! -d "$src/.git" ] || [ "$DRY" = 1 ]; then
        run rm -rf "$src"
        run git clone --depth 1 --branch "$ZMF_BWRAP_TAG" https://github.com/containers/bubblewrap "$src" \
            || die "cannot clone bubblewrap tag '$ZMF_BWRAP_TAG'. Set ZMF_BWRAP_TAG to a release >= $BWRAP_MIN that exists, or install a newer bubblewrap yourself"
    fi
    # option names (man, tests) are from memory; fall back to a plain configure if meson rejects them.
    if ! run meson setup "$src/_b" "$src" --prefix "$PREFIX" -Dman=disabled -Dtests=false; then
        run rm -rf "$src/_b"
        run meson setup "$src/_b" "$src" --prefix "$PREFIX"
    fi
    run ninja -C "$src/_b" -j "$(build_jobs)"
    run meson install -C "$src/_b"
    load_env
    if [ "$DRY" = 0 ]; then
        v=$("$PREFIX/bin/bwrap" --version 2>/dev/null | awk '{print $2}')
        version_ge "${v:-0}" "$BWRAP_MIN" || die "built bubblewrap reports '${v:-?}', still < $BWRAP_MIN"
        log "bubblewrap $v installed in $PREFIX/bin (env.sh puts it first on PATH for zmd)"
    fi
}

build_zm() {
    step "building zeromesh (ninja -j$(build_jobs))"
    load_env
    if [ ! -d "$VENV" ]; then
        # meson records the python interpreter at configure time, so the venv comes first.
        run python3 -m venv "$VENV"
        run "$VENV/bin/pip" install --quiet "$ROOT/sdk/python[dev]"
        load_env
    fi
    if [ ! -f "$BUILD/build.ninja" ]; then run meson setup "$BUILD" "$ROOT"; fi
    run ninja -C "$BUILD" -j "$(build_jobs)"
    if [ "$DRY" = 0 ]; then
        [ -x "$BUILD/zm" ] && [ -x "$BUILD/zmd" ] || die "build finished but $BUILD/zm or zmd is missing"
        log "built: $("$BUILD/zm" version 2>/dev/null | head -1) in $BUILD"
    fi
}

open_firewall() {
    step "opening firewall ports (8981/tcp 8988/udp 9618/tcp)"
    if have firewall-cmd && systemctl is-active --quiet firewalld 2>/dev/null; then
        as_root firewall-cmd --permanent --add-port=8981/tcp --add-port=8988/udp --add-port=9618/tcp
        as_root firewall-cmd --reload
    elif have ufw; then
        as_root ufw allow 8981/tcp; as_root ufw allow 8988/udp; as_root ufw allow 9618/tcp
    elif have iptables; then
        warn "plain iptables rules are not persistent across reboot"
        as_root iptables -I INPUT -p tcp --dport 8981 -j ACCEPT
        as_root iptables -I INPUT -p udp --dport 8988 -j ACCEPT
        as_root iptables -I INPUT -p tcp --dport 9618 -j ACCEPT
    else
        warn "no ufw/firewalld/iptables found; open the ports yourself if anything blocks"
    fi
}

cmd_setup() {
    local want_condor=1 fw=0 branch=""
    while [ $# -gt 0 ]; do
        case "$1" in
        --no-condor) want_condor=0 ;;
        --open-firewall) fw=1 ;;
        --branch) branch=${2:?--branch needs a value}; shift ;;
        *) die "setup: unknown option $1" ;;
        esac
        shift
    done
    load_env
    if [ -n "$branch" ]; then
        step "checking out $branch"
        run git -C "$ROOT" fetch origin "$branch" || warn "fetch failed; using local $branch if it exists"
        run git -C "$ROOT" checkout "$branch"
    fi
    install_deps
    ensure_bwrap
    build_zm
    write_env_sh
    if [ "$want_condor" = 1 ]; then condor_install; else log "skipping HTCondor (--no-condor)"; fi
    if [ "$fw" = 1 ]; then open_firewall; fi
    step "setup done"
    log "next: bash scripts/zmfield.sh doctor   then   selftest   then   requester / donor"
}

# ---------------------------------------------------------------------------------------
# selftest: meson test, summarised
# ---------------------------------------------------------------------------------------
cmd_selftest() {
    load_env
    local out=$ZMF_HOME/selftest.log rc=0
    step "meson test (log: $out)"
    if [ "$DRY" = 1 ]; then log "(dry-run) meson test -C $BUILD --print-errorlogs"; return 0; fi
    [ -f "$BUILD/build.ninja" ] || die "not built: run setup first"
    mkdir -p "$ZMF_HOME"
    set +e
    env -u ZM_STATE_DIR -u ZM_RUNTIME_DIR -u ZM_CONFIG_DIR -u ZM_PLUGIN_PATH \
        meson test -C "$BUILD" --print-errorlogs >"$out" 2>&1
    rc=$?
    set -e
    grep -E '^ *[0-9]+/[0-9]+ .* (OK|FAIL|SKIP|TIMEOUT|ERROR|EXPECTEDFAIL|UNEXPECTEDPASS) ' "$out" || true
    printf '\nOK: %s  FAIL: %s  SKIP: %s  TIMEOUT/ERROR: %s   (meson exit %s)\n' \
        "$(grep -cE '^ *[0-9]+/[0-9]+ .* OK ' "$out" || true)" \
        "$(grep -cE '^ *[0-9]+/[0-9]+ .* FAIL ' "$out" || true)" \
        "$(grep -cE '^ *[0-9]+/[0-9]+ .* SKIP ' "$out" || true)" \
        "$(grep -cE '^ *[0-9]+/[0-9]+ .* (TIMEOUT|ERROR) ' "$out" || true)" "$rc"
    log "tests that need blender, recc or /dev/fuse fail on machines without them; read the log before blaming zeromesh"
    return "$rc"
}

# ---------------------------------------------------------------------------------------
# zeromesh daemon control
# ---------------------------------------------------------------------------------------
ZM() { "$BUILD/zm" --socket "$SOCK" "$@"; }
ZMD_PID=$ZM_DIR/zmd.pid

zmd_alive() {
    local p
    [ -f "$ZMD_PID" ] || return 1
    p=$(cat "$ZMD_PID")
    [ -n "$p" ] && [ -r "/proc/$p/comm" ] && [ "$(cat "/proc/$p/comm")" = zmd ]
}

write_donor_toml() {
    run mkdir -p "$ZM_CONFIG_DIR"
    [ "$DRY" = 1 ] && { log "(dry-run) would write $ZM_CONFIG_DIR/donor.toml"; return 0; }
    cat >"$ZM_CONFIG_DIR/donor.toml" <<'EOF'
# written by zmfield.sh so laptops on battery still donate during a test.
# max_cores is left at its default (cores_total - 1).
allow_on_battery_above = 0
drain_below_battery = 0
EOF
}

zmd_start() {
    [ -x "$BUILD/zmd" ] || die "no $BUILD/zmd: run setup first"
    run mkdir -p "$ZM_STATE_DIR" "$ZM_RUNTIME_DIR" "$ZM_CONFIG_DIR"
    write_donor_toml
    if [ "$DRY" = 1 ]; then log "(dry-run) would start $BUILD/zmd with state under $ZM_DIR"; return 0; fi
    if zmd_alive; then log "zmd already running (pid $(cat "$ZMD_PID"))"; return 0; fi
    rm -f "$SOCK"
    nohup "$BUILD/zmd" >"$ZM_DIR/zmd.log" 2>&1 &
    echo $! >"$ZMD_PID"
    local i
    for i in $(seq 1 100); do
        if ZM status >/dev/null 2>&1; then log "zmd up (pid $(cat "$ZMD_PID"), log $ZM_DIR/zmd.log)"; return 0; fi
        sleep 0.1
    done
    die "zmd did not come up; see $ZM_DIR/zmd.log"
}

zmd_stop() {
    zmd_alive || return 0
    local p; p=$(cat "$ZMD_PID")
    run kill -TERM "$p"
    [ "$DRY" = 1 ] && return 0
    local i
    for i in $(seq 1 100); do kill -0 "$p" 2>/dev/null || return 0; sleep 0.1; done
    kill -KILL "$p" 2>/dev/null || true
}

admitted_peers() {
    ZM status 2>/dev/null | awk '$1 ~ /^[0-9a-f]{8}$/ && $NF=="yes"{c++} END{print c+0}'
}

wait_admitted() { # wait_admitted SECONDS -> 0 if >=1 admitted peer
    [ "$DRY" = 1 ] && return 0
    local i n=${1:-60}
    for i in $(seq 1 "$n"); do
        if [ "$(admitted_peers)" -ge 1 ]; then return 0; fi
        sleep 1
    done
    return 1
}

# ---------------------------------------------------------------------------------------
# HTCondor
#
# NOTE: the knob names, the CLAIMTOBE authentication setup and the drop-in ordering below were
# written from memory and have NOT been checked against a running pool. condor_verify prints the
# effective values so a mismatch is visible; if the pool does not form, read /var/log/condor/*.
# ---------------------------------------------------------------------------------------
condor_have_native() {
    { have condor_master || [ -x /usr/sbin/condor_master ]; } && have condor_submit
}

condor_tier() {
    local f=$ZMF_HOME/condor.tier
    if [ -f "$f" ]; then cat "$f"; return; fi
    if condor_have_native; then echo native
    elif [ -n "$(ctr)" ] && "$(ctr)" container exists "$CNAME" >/dev/null 2>&1; then echo container
    else echo none; fi
}

condor_install() {
    step "HTCondor (native packages, else official installer, else container)"
    detect_os
    local tier=none
    if condor_have_native; then
        log "HTCondor already installed natively"; tier=native
    else
        case "$PM" in
        apt) as_root apt-get install -y htcondor || true ;;
        dnf) as_root dnf install -y condor || true ;;
        zypper) as_root zypper --non-interactive install condor || true ;;
        pacman) log "no HTCondor package in the official Arch repos; trying other tiers" ;;
        esac
        if condor_have_native; then tier=native
        elif [ "$PM" = apt ] || [ "$PM" = dnf ]; then
            log "trying HTCondor's official installer (get.htcondor.org, --minicondor)"
            local tmp=$ZMF_HOME/get-htcondor.sh
            run mkdir -p "$ZMF_HOME"
            if run curl -fsSL https://get.htcondor.org -o "$tmp" && as_root bash "$tmp" --no-dry-run --minicondor; then
                if condor_have_native; then tier=native; fi
            else
                warn "official installer failed"
            fi
        fi
    fi
    if [ "$tier" = none ]; then
        local c; c=$(ctr)
        if [ -n "$c" ]; then
            warn "falling back to the $c container ($CONDOR_IMAGE); the cross-host container path is UNTESTED"
            run "$c" pull "$CONDOR_IMAGE"
            tier=container
        else
            warn "no HTCondor and no podman/docker: HTCondor runs will be skipped"
        fi
    fi
    run mkdir -p "$ZMF_HOME"
    if [ "$DRY" = 0 ]; then echo "$tier" >"$ZMF_HOME/condor.tier"; fi
    log "HTCondor tier: $tier"
}

condor_cmd() { # run a condor CLI as the submit user
    case "$(condor_tier)" in
    native) "$@" ;;
    container) "$(ctr)" exec -u submituser "$CNAME" "$@" ;;
    *) die "no HTCondor available" ;;
    esac
}

# condor_conf_text ROLE CM_IP MY_IP PEER_IP
condor_conf_text() {
    local role=$1 cm=$2 me=$3 peer=${4:-} daemons allow ncpu
    if [ "$role" = requester ]; then daemons="MASTER COLLECTOR NEGOTIATOR SCHEDD STARTD"; else daemons="MASTER STARTD"; fi
    if [ -n "$peer" ]; then allow=$(printf '%s\n' 127.0.0.1 "$me" "$cm" "$peer" | awk 'NF && !seen[$0]++' | paste -sd, - | sed 's/,/, /g')
    else allow="127.0.0.1, ${me%.*}.*"; fi
    ncpu=$(( $(nproc) - 1 )); [ "$ncpu" -ge 1 ] || ncpu=1
    cat <<EOF
# generated by zmfield.sh ($role). Test pool only: CLAIMTOBE auth trusts the IP allow-list below.
CONDOR_HOST = $cm
NETWORK_INTERFACE = $me
DAEMON_LIST = $daemons
# one core stays free for the owner, same as zmd's default (cores_total - 1)
NUM_CPUS = $ncpu
START = TRUE
SUSPEND = FALSE
PREEMPT = FALSE
KILL = FALSE
WANT_SUSPEND = FALSE
WANT_VACATE = FALSE
SEC_DEFAULT_AUTHENTICATION = REQUIRED
SEC_DEFAULT_AUTHENTICATION_METHODS = CLAIMTOBE
SEC_DEFAULT_ENCRYPTION = OPTIONAL
SEC_DEFAULT_INTEGRITY = OPTIONAL
ALLOW_READ = $allow
ALLOW_WRITE = $allow
ALLOW_DAEMON = $allow
ALLOW_NEGOTIATOR = $allow
ALLOW_ADMINISTRATOR = $allow
EOF
}

# condor_start ROLE CM_IP MY_IP PEER_IP
condor_start() {
    local role=$1 cm=$2 me=$3 peer=${4:-} tier
    tier=$(condor_tier)
    if [ "$tier" = none ]; then warn "no HTCondor on this machine; skipping (run setup without --no-condor)"; return 0; fi
    step "starting HTCondor ($role, $tier tier)"
    if [ -z "$peer" ]; then
        warn "no --peer given: HTCondor allow-list is the whole ${me%.*}.0/24 with CLAIMTOBE auth. Anyone on that subnet can submit jobs to this pool. Do not do this on a shared network."
    fi
    local dir=$ZMF_HOME/condor conf
    conf=$dir/99-zmfield.conf
    run mkdir -p "$dir"
    if [ "$DRY" = 1 ]; then
        log "(dry-run) config would be:"; condor_conf_text "$role" "$cm" "$me" "$peer" | sed 's/^/    /'
    else
        condor_conf_text "$role" "$cm" "$me" "$peer" >"$conf"
    fi
    case "$tier" in
    native)
        as_root install -d -m 0755 /etc/condor/config.d
        as_root install -m 0644 "$conf" /etc/condor/config.d/99-zmfield.conf
        if have systemctl; then
            as_root systemctl enable condor || true
            as_root systemctl restart condor
        else
            as_root pkill -x condor_master || true
            as_root condor_master
        fi ;;
    container)
        local c; c=$(ctr)
        run "$c" rm -f "$CNAME" || true
        run "$c" run -d --name "$CNAME" --network host --uts host \
            -v "$conf:/etc/condor/config.d/99-zmfield.conf:ro,Z" "$CONDOR_IMAGE" ;;
    esac
    if [ "$role" = requester ]; then condor_verify "$cm"; else
        log "donor HTCondor started; the requester's 'bench' checks that this machine's slot shows up"
    fi
}

condor_verify() {
    [ "$DRY" = 1 ] && return 0
    local cm=$1 i n=0
    log "waiting up to 90s for the local startd to appear in condor_status"
    for i in $(seq 1 45); do
        n=$(condor_cmd condor_status -af Machine 2>/dev/null | sort -u | wc -l) || n=0
        if [ "$n" -ge 1 ]; then break; fi
        sleep 2
    done
    log "effective CONDOR_HOST: $(condor_cmd condor_config_val CONDOR_HOST 2>/dev/null || echo '?') (expected $cm)"
    log "effective DAEMON_LIST: $(condor_cmd condor_config_val DAEMON_LIST 2>/dev/null || echo '?')"
    if [ "$n" -lt 1 ]; then
        warn "no machines in condor_status. Diagnostics: tail /var/log/condor/MasterLog /var/log/condor/CollectorLog /var/log/condor/StartLog; check that 99-zmfield.conf is picked up (condor_config_val -config) and that 9618/tcp is open"
        return 0
    fi
    log "pool machines: $(condor_cmd condor_status -af Machine 2>/dev/null | sort -u | tr '\n' ' ')"
}

condor_stop() {
