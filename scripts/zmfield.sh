# report
# ---------------------------------------------------------------------------------------
cmd_report() {
    local d=${1:-}
    if [ -z "$d" ]; then d=$(ls -1d "$ZMF_HOME"/results/*/ 2>/dev/null | tail -n1 || true); d=${d%/}; fi
    [ -n "$d" ] && [ -f "$d/results.csv" ] || die "no results found (looked in ${d:-$ZMF_HOME/results})"
    local md=$d/report.md
    {
        echo "# ZeroMesh vs HTCondor field test"
        echo
        echo "## Environment (requester)"
        echo '```'
        cat "$d/hostinfo.txt" 2>/dev/null || true
        echo '```'
        echo
        echo "## Results"
        echo
        echo "Wall time is submit to last result back. MB are rx/tx on the requester NIC during the run (other traffic on that NIC is included). The ratio is wall time divided by the \`zm-local\` single-machine baseline for the same workload and step."
        echo
        echo "| workload | step | system | variant | wall s | vs zm-local | MB rx / tx | ok | retries | notes |"
        echo "|---|---|---|---|---|---|---|---|---|---|"
        awk -F, 'NR==FNR{ if($3=="zm-local" && $4=="none") b[$1","$2]=$5; next }
            FNR>1{ k=$1","$2; r=(k in b && b[k]>0)? sprintf("%.2fx", $5/b[k]) : "n/a";
                   printf "| %s | %s | %s | %s | %s | %s | %s / %s | %s/%s | %s | %s |\n", $1,$2,$3,$4,$5,r,$6,$7,$8,$9,$10,$11 }' \
            "$d/results.csv" "$d/results.csv"
        echo
        echo "## Not measured here"
        echo
        echo "- Owner comfort (what the donor's owner feels while tasks run)."
        echo "- Freeze-first departure on a real lid close, suspend or unplug (this bench only kills or stops processes)."
        echo "- The effect of tail hedging on its own (it is on in the zm runs; there is no off switch used here)."
        echo "- Cold versus warm donor caches across repeated bench runs, and Wi-Fi variance between runs."
        echo "- HTCondor numbers are for the config this script wrote, with the tuned knobs applied on the requester only."
    } >"$md"
    log "report: $md"
    cat "$md"
}

# ---------------------------------------------------------------------------------------
usage() {
    cat <<'EOF'
zmfield.sh: field-test ZeroMesh against HTCondor on real Linux laptops.
Run with bash (fish users: `bash scripts/zmfield.sh ...`). Global flag: --dry-run (print, don't execute).
Env: ZMF_HOME (default ~/.zmfield), ZMF_JOBS (build -j), ZMF_BWRAP_TAG, ZMF_TIMEOUT, ZMF_KEEP_WORK=1.

  doctor                                  check this machine (read-only)
  setup [--no-condor] [--open-firewall] [--branch B]
                                          install deps, build zeromesh, install HTCondor
  selftest                                meson test, summarised (needs setup)
  requester [--ip IP] [--peer DONOR_IP] [--condor-mode default|tuned]
                                          start zmd + create team + HTCondor central manager/submit;
                                          prints the exact command to run on the donor
  donor --cm REQUESTER_IP [--join 'ZM-..'] [--ip IP]
                                          start zmd + join team + HTCondor execute node
  bench [--workloads w1,w2,w3] [--cases N] [--secs S] [--mb MB] [--all-nodes]
        [--ssh user@donor] [--ssh-script PATH] [--condor-modes default,tuned]
        [--peer DONOR_IP] [--with-term]   (run on the requester)
                                          w1 CPU fan-out, w2 data-once, w3 donor churn
  chaos <zm|condor> <kill|term|restore>   run on the donor: break or restore it (bench calls this)
  report [DIR]                            regenerate report.md from a results directory
  down                                    stop zmd and HTCondor (removes the HTCondor drop-ins)

Two-laptop recipe: see scripts/ZMFIELD.md
EOF
}

main() {
    local args=() a
    for a in "$@"; do
        if [ "$a" = --dry-run ]; then DRY=1; else args+=("$a"); fi
    done
    set -- ${args[@]+"${args[@]}"}
    local cmd=${1:-}
    [ $# -gt 0 ] && shift
    if [ "${BASH_VERSINFO[0]}" -lt 4 ]; then die "bash >= 4 required"; fi
    case "$cmd" in
    doctor) cmd_doctor "$@" ;;
    setup) cmd_setup "$@" ;;
    selftest) cmd_selftest "$@" ;;
    requester) cmd_requester "$@" ;;
    donor) cmd_donor "$@" ;;
    bench) cmd_bench "$@" ;;
    chaos) cmd_chaos "$@" ;;
    report) cmd_report "$@" ;;
    down) cmd_down "$@" ;;
    ""|-h|--help|help) usage ;;
    *) usage >&2; die "unknown command: $cmd" ;;
    esac
}

# allow `source zmfield.sh` for testing individual functions
if [ "${BASH_SOURCE[0]}" = "$0" ]; then main "$@"; fi
